"""Batched decoding with a KV cache and online tripwires.

The gate is evaluated at every position whose state influences the output: all prompt positions after the
fixed chat-template prefix (state.gate_from) and every generated token except the last one (an end-of-sequence token, or the token at the length limit, is never fed
back). Tokens after a sequence has finished are padding and are excluded.

Batches are formed by sorting prompts by length (longest first, ties by index), so the same prompt list is
always split into the same batches. This keeps greedy outputs bit-identical across stages wherever no new
tripwire fires (Theorem 3.2), which the evaluation checks. Sampling reads its uniforms from a table U[prompt index,
step] drawn once per call from (seed), so a prompt's random numbers depend neither on which batch it lands in nor
on the number of GPUs or the batch size.

Multi-GPU (see twcore/dist.py): batch b is generated by rank b % world and the results are gathered, so every
rank returns the same list, identical to a single-GPU run on the same GPU type.
"""
from __future__ import annotations

from typing import Iterable, List, Optional

import torch

from . import dist
from .gating import GateState


def _left_pad(batch: List[List[int]], pad_id: int, device):
    T = max(len(p) for p in batch)
    ids = torch.full((len(batch), T), pad_id, dtype=torch.long, device=device)
    attn = torch.zeros((len(batch), T), dtype=torch.long, device=device)
    for j, p in enumerate(batch):
        if len(p) == 0:
            raise ValueError("empty prompt")
        ids[j, T - len(p):] = torch.tensor(p, dtype=torch.long, device=device)
        attn[j, T - len(p):] = 1
    return ids, attn


@torch.no_grad()
def _generate_batch(model, state: GateState, batch: List[List[int]], *, pad_id: int, stop: Iterable[int],
                    max_new_tokens: int, greedy: bool, temperature: float, uniforms, record: bool,
                    top_p: float = 1.0) -> List[dict]:
    """uniforms: [len(batch), max_new_tokens] (sampling only), one uniform per sequence and step.
    top_p < 1: nucleus sampling, a fixed transformation of the next-token distribution before the same inverse-CDF
    step, so it is still a decoding rule in the sense of Theorem 3.2."""
    device = next(model.parameters()).device
    B = len(batch)
    ids, attn = _left_pad(batch, pad_id, device)
    pos = (attn.cumsum(-1) - 1).clamp(min=0)
    stop_t = torch.tensor(sorted(set(stop)), dtype=torch.long, device=device)
    pad_t = torch.full((B,), pad_id, dtype=torch.long, device=device)

    state.begin("incremental", record=record and state.has_scoring())
    try:
        if state.last_prompt_only:   # left padding: the last column is every prompt's last token
            valid0 = torch.zeros_like(attn, dtype=torch.bool)
            valid0[:, -1] = True
            state.valid = valid0
        else:
            state.valid = attn.bool() & (pos >= state.gate_from)
        out = model.model(input_ids=ids, attention_mask=attn, position_ids=pos, use_cache=True)
        past = out.past_key_values
        logits = model.lm_head(out.last_hidden_state[:, -1]).float()
        cur = pos[:, -1]
        finished = torch.zeros(B, dtype=torch.bool, device=device)
        toks = []
        for step in range(max_new_tokens):
            if greedy:
                nxt = logits.argmax(dim=-1)
            else:
                # inverse-CDF sampling with one uniform per sequence and step: the token of row j depends only on
                # row j's distribution and its own uniform, which is the shared-randomness decoding rule of
                # Theorem 3.2 (two models fed the same uniforms emit the same tokens until their distributions differ)
                probs = torch.softmax(logits / temperature, dim=-1)
                if top_p < 1.0:   # keep the smallest set of most likely tokens whose mass reaches top_p
                    sp, si = probs.sort(dim=-1, descending=True, stable=True)   # ties: lower token id first
                    keep = (sp.cumsum(dim=-1) - sp) < top_p          # the most likely token is always kept
                    probs = probs * torch.zeros_like(keep).scatter_(-1, si, keep).to(probs.dtype)
                u = uniforms[:, step:step + 1].to(probs.dtype)
                cdf = probs.cumsum(dim=-1)
                nxt = torch.searchsorted(cdf, u * cdf[:, -1:], right=True).squeeze(-1).clamp_(max=probs.shape[-1] - 1)
            nxt = torch.where(finished, pad_t, nxt)
            toks.append(nxt)
            finished = finished | torch.isin(nxt, stop_t)
            if step == max_new_tokens - 1 or bool(finished.all()):
                break
            attn = torch.cat([attn, torch.ones((B, 1), dtype=attn.dtype, device=device)], dim=1)
            cur = cur + 1
            state.valid = torch.zeros_like(finished)[:, None] if state.last_prompt_only else (~finished)[:, None]
            out = model.model(input_ids=nxt[:, None], attention_mask=attn, position_ids=cur[:, None],
                              past_key_values=past, use_cache=True)
            past = out.past_key_values
            logits = model.lm_head(out.last_hidden_state[:, -1]).float()
        rec = state.end()
    except BaseException:
        state.end()
        raise

    gen = torch.stack(toks, dim=1).cpu().tolist()
    stop_set = set(int(s) for s in stop)
    results = []
    for j in range(B):
        seq = []
        for t in gen[j]:
            seq.append(int(t))
            if t in stop_set:
                break
        results.append({"out": seq, "plen": len(batch[j]), "fire": {}, "maxs": {}})

    if rec:
        kappas = {t: float(state.tripwires[t].kappa) for t in state.tripwires}
        P = state.gate_from
        for tid, chunks in rec.items():
            S = torch.cat([c[0] for c in chunks], dim=1).cpu()
            V = torch.cat([c[1] for c in chunks], dim=1).cpu()
            for j in range(B):
                s = S[j][V[j]]
                plen = len(batch[j])
                n_expected = 1 if state.last_prompt_only else plen + len(results[j]["out"]) - 1 - min(P, plen)
                if s.numel() != n_expected:
                    raise RuntimeError(f"recorded {s.numel()} gate positions, expected {n_expected}")
                results[j]["maxs"][tid] = float(s.max()) if s.numel() else float("-inf")
                if tid in kappas:
                    above = torch.nonzero(s > kappas[tid]).flatten()
                    if not above.numel():
                        results[j]["fire"][tid] = None
                    elif state.last_prompt_only:
                        results[j]["fire"][tid] = -1          # the last prompt token
                    else:
                        results[j]["fire"][tid] = int(above[0]) + P - plen
    return results


def generate(model, state: GateState, prompts: List[List[int]], *, pad_id: int, stop: Iterable[int],
             max_new_tokens: int, batch_size: int, greedy: bool = True, temperature: float = 1.0,
             seed: int = 0, record: bool = False, progress=None, distributed: bool = True,
             top_p: float = 1.0) -> List[dict]:
    """Returns, per prompt (input order): out (response ids, ending with the stop token if one was produced),
    plen, fire {tripwire id: first firing position relative to the end of the prompt, or None} and
    maxs {tripwire id: max score over gate positions} (fire/maxs only when record=True).
    With distributed=True (default) and several ranks, every rank must call this with the same prompts."""
    device = next(model.parameters()).device
    order = sorted(range(len(prompts)), key=lambda i: (-len(prompts[i]), i))
    batches = [order[b0:b0 + batch_size] for b0 in range(0, len(order), batch_size)]
    W, me = (dist.world(), dist.rank()) if distributed else (1, 0)
    results: List[Optional[dict]] = [None] * len(prompts)
    mine = []
    U = None
    if not greedy:  # every rank draws the same table
        gen = torch.Generator(device=device)
        gen.manual_seed(int(seed) % (2 ** 62))
        U = torch.rand((len(prompts), max_new_tokens), generator=gen, device=device, dtype=torch.float32)
    for bi, idx in enumerate(batches):
        if bi % W != me:
            continue
        res = _generate_batch(model, state, [prompts[i] for i in idx], pad_id=pad_id, stop=stop,
                              max_new_tokens=max_new_tokens, greedy=greedy, temperature=temperature,
                              uniforms=None if U is None else U[idx], record=record, top_p=top_p)
        for i, r in zip(idx, res):
            results[i] = r
            mine.append((i, r))
        if progress is not None:
            progress(min((bi + 1) * batch_size, len(order)), len(order))
    if W > 1:
        for part in dist.all_gather(mine):
            for i, r in part:
                results[i] = r
    return results  # type: ignore[return-value]
